"""
Единая точка входа для запуска на платформах, где команда запуска идёт
без shell-обёртки (exec-форма CMD в Docker) — там оператор "&&" не работает,
он воспринимается как обычный текстовый аргумент, а не разделитель команд.

Этот файл сам, внутри одного Python-процесса, сначала накатывает seed,
потом поднимает uvicorn — никакого "&&" в команде запуска не требуется.

Команда запуска (на SpaceWeb Serverless и подобных):
    python start.py

Порт и хост берутся из переменных окружения PORT (если платформа их задаёт)
с разумными значениями по умолчанию для локального запуска.
"""
import os
import subprocess
import sys

import uvicorn

if __name__ == "__main__":
    # 1. Прогоняем seed (создание таблиц + демо-данные). Не валим процесс,
    #    если seed вдруг упадёт на "уже существует" и т.п. — сервер всё равно
    #    должен подняться.
    subprocess.run([sys.executable, "-m", "app.seed"], check=False)

    # 2. Стартуем сам сервер в этом же процессе.
    port = int(os.environ.get("PORT", 8123))
    uvicorn.run("app.main:app", host="0.0.0.0", port=port)
